#!/usr/bin/env python3
"""Generate the SYNTHETIC placeholder base file data/bases/yumen.json.

The output is a regular hexagonal lattice, not real silo positions. It only
roughly matches the publicly reported scale of the Yumen field (about 120 silos,
about 3 km apart) so the frontend has something realistic-looking to draw
until verified coordinates are added.

Usage:  python3 scripts/make_placeholder_grid.py
Standard library only.
"""

import json
import math
from pathlib import Path

# Approximate centre of the reported field area. Deliberately coarse.
CENTER_LAT = 40.15
CENTER_LON = 96.65
SPACING_M = 2900  # nearest-neighbour distance on the lattice
COUNT = 118
METERS_PER_DEG_LAT = 111_320

OUT = Path(__file__).resolve().parent.parent / "data" / "bases" / "yumen.json"


def hex_lattice(n_wanted: int, spacing: float) -> list[tuple[float, float]]:
    """Return the n lattice points (east, north in metres) closest to the origin."""
    row_h = spacing * math.sqrt(3) / 2
    radius = int(math.sqrt(n_wanted)) + 3
    pts = []
    for j in range(-radius, radius + 1):
        for i in range(-radius, radius + 1):
            x = (i + (0.5 if j % 2 else 0.0)) * spacing
            y = j * row_h
            pts.append((math.hypot(x, y), -y, x))  # sort key: distance, then north->south, west->east
    pts.sort()
    return [(x, -neg_y) for _, neg_y, x in pts[:n_wanted]]


def main() -> None:
    pts = hex_lattice(COUNT, SPACING_M)
    pts.sort(key=lambda p: (-p[1], p[0]))  # number silos north->south, west->east
    m_per_deg_lon = METERS_PER_DEG_LAT * math.cos(math.radians(CENTER_LAT))
    silos = [
        {
            "id": f"Y{k:03d}",
            "lat": round(CENTER_LAT + y / METERS_PER_DEG_LAT, 5),
            "lon": round(CENTER_LON + x / m_per_deg_lon, 5),
        }
        for k, (x, y) in enumerate(pts, start=1)
    ]
    base = {
        "id": "yumen",
        "name": "Yumen",
        "country": "China",
        "dataStatus": "placeholder",
        "source": (
            "SYNTHETIC PLACEHOLDER — not real silo coordinates. A regular hexagonal grid "
            f"of {COUNT} points at {SPACING_M / 1000:.1f} km spacing, centred near the approximate "
            "area of the publicly reported Yumen field. Generated by "
            "scripts/make_placeholder_grid.py. Replace with verified data."
        ),
        "silos": silos,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(base, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(silos)} silos to {OUT}")


if __name__ == "__main__":
    main()
